package a2261330031_practica4;

public class Ejercicio4 {
    public static void main(String[] args) {
        double promedio = 9.5784;
        double pi = Math.PI;

        System.out.printf("Promedio sin formato: %f\n", promedio);
        System.out.printf("Promedio con 2 decimales: %.2f\n", promedio);
        System.out.printf("Promedio con 1 decimal: %.1f\n", promedio);
        System.out.printf("Valor de PI con 4 decimales: %.4f\n", pi);
    }
}